    /** Find one price-list item by id. Stops the build with a clear message if the id is wrong. */
    export function getPriceItem(id: string): PriceListItem {
      const item = priceList.find((entry) => entry.id === id);
      if (!item) {
        throw new Error(`Price list item "${id}" not found in src/data/pricelist.ts`);
      }
      return item;
    }

    /**
     * Get one price, e.g. priceOf("balinese-massage", "1 Hour") -> 159000.
     * Treatment pages use this so a price is only ever typed once.
     */
    export function priceOf(id: string, label: string): number {
      const option = getPriceItem(id).options.find((entry) => entry.label === label);
      if (!option) {
        throw new Error(`Price "${label}" not found for "${id}" in src/data/pricelist.ts`);
      }
      return option.price;
    }
    